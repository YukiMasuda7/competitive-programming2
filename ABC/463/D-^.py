# 区間スケジューリング？
# -> 終了点の小さい順にソート。重ならない区間の数を最大化
# 重ならない区間の数がKを超えるのはOK -> その中からK個抽出すればいいだけだから
# 重ならない区間を最大化してあとは典型1(羊羹パーティーの問題)みたいに二分探索？

# 距離がx以上の区間をK個以上作れるか
# 区間スケジューリングしたらダメでは ->　区間候補が制限されてしまう？

# --- コンテスト後メモ ---

# 1) なぜ「右端 R 昇順」が必要？
# check(x) の貪欲は「次を選べる区間の候補をなるべく残す」ため、
# 選べるなら右端が最も小さい区間を取るのが最適です。

# 左端ソートだと失敗例があります（x=1）:

# [1,100], [2,3], [4,5]
# 左端順で最初 [1,100] を取ると後が全部取れない。
# でも実際は [2,3] と [4,5] を取れます。
# → 左端基準の貪欲は壊れる。


# 2) なぜ prev=0 はダメ？
# 1枚目には「前の布」がないので、距離制約は本来ありません。
# でも prev=0 にすると1枚目にも L-prev>=x を課してしまいます。

# 例（x=5, K=2）:

# [1,2], [10,11]
# 本来は2枚選べて True。
# しかし prev=0 だと最初 [1,2] が 1-0<5 で弾かれ、誤って False になる。




N, K = map(int, input().split())
A = []
for i in range(N):
    L, R = map(int, input().split())
    A.append([L, R])

A.sort(key=lambda t: t[1])


def check(x):
    cnt = 0
    prev_r = -(10**10)
    for l, r in A:
        if l - prev_r >= x:
            cnt += 1
            prev_r = r
            if cnt >= K:
                return True
    return False


if not check(1):
    print(-1)
    exit()

l = 1
r = 10**9 + 1

while r - l > 1:
    m = (l + r) // 2
    if check(m):
        l = m
    else:
        r = m

print(l)
